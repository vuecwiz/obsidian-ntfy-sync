export interface I18n {
  readonly locale: PluginLocale;
  t(key: TranslationKey, variables?: Record<string, string | number>): string;
}

export function createI18n(
  preference: UiLanguageSetting,
  hostLanguage = currentHostLanguage(),
): I18n {
  const locale = resolvePluginLocale(preference, hostLanguage);
  const messages = locale === "zh-CN" ? ZH_CN : EN;
  return {
    locale,
    t(key, variables = {}) {
      return interpolate(messages[key], variables);
    },
  };
}

export function resolvePluginLocale(
  preference: UiLanguageSetting,
  hostLanguage: string,
): PluginLocale {
  if (preference === "en" || preference === "zh-CN") return preference;
  return hostLanguage.toLocaleLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function currentHostLanguage(): string {
  return window.document?.documentElement.lang || "en";
}

export function conditionFieldLabel(i18n: I18n, field: ConditionV1["field"]): string {
  return i18n.t(`field.${field}` as TranslationKey);
}

export function conditionOperatorLabel(
  i18n: I18n,
  field: ConditionV1["field"],
  operator: string,
): string {
  if (field === "tag" && operator === "contains") return i18n.t("operator.tagIs");
  const key = `operator.${operator}` as TranslationKey;
  return key in EN ? i18n.t(key) : operator;
}

export function mimePresetLabel(i18n: I18n, value: string, fallback: string): string {
  const key = `mime.${value}` as TranslationKey;
  return key in EN ? i18n.t(key) : fallback;
}

export function summarizeRuleLocalized(
  rule: RuleV1,
  i18n: I18n,
): { name: string; notePath: string; description: string } {
  const conditions = rule.when.all.length
    ? rule.when.all
        .map((condition) => summarizeConditionLocalized(condition, i18n))
        .join(i18n.t("summary.and"))
    : i18n.t("summary.allMessages");
  const summary = `${rule.enabled ? "" : i18n.t("summary.disabled")}${conditions}`;
  return {
    name: rule.name,
    notePath: rule.action.notePathTemplate,
    description: summary.length > 96 ? `${summary.slice(0, 93)}…` : summary,
  };
}

export function localizeValidationIssue(i18n: I18n, issue: ValidationIssue): string {
  if (i18n.locale === "en") return issue.message;
  const key = `validation.${issue.code}` as TranslationKey;
  return i18n.t(key in EN ? key : "validation.default");
}

function summarizeConditionLocalized(condition: ConditionV1, i18n: I18n): string {
  const field = conditionFieldLabel(i18n, condition.field);
  if (condition.field === "hasAttachment" || condition.field === "hasHttpUrl") {
    return `${field}：${i18n.t(condition.value ? "summary.yes" : "summary.no")}`;
  }
  if (condition.field === "firstUrlHost") {
    const relation = i18n.t(
      condition.op === "hostEquals" ? "summary.hostEquals" : "summary.hostOrSubdomain",
    );
    return `${field} ${relation} “${condition.value}”`;
  }
  const operator = conditionOperatorLabel(i18n, condition.field, condition.op);
  const value =
    typeof condition.value === "string" ? `“${condition.value}”` : String(condition.value);
  return `${field} ${operator} ${value}`;
}

function interpolate(template: string, variables: Record<string, string | number>): string {
  return template.replace(/\{([a-zA-Z0-9_]+)\}/gu, (match, key: string) =>
    Object.hasOwn(variables, key) ? String(variables[key]) : match,
  );
}
